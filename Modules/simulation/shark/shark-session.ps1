    "                                  :+++++*:                                                          "
    "                                 .=+++++*.                                                          "
    "                        ::      .-+++++++.                                                          "
    "                       .+:    .-=+++++++*.                                                          "
    "                       :+. .:=++=---++++*-                                                          "
    "                      .=+:-++=-.    .-=+++.                                                         "
    "                      .++*++-.        .:-==.                                                        "
    "                      -*==+.              .                                                         "
    "                    .=*+=+*-.           .::...                                                      "
    "                   .+*+=+-::.           .**++==-..                                                  "
