    "                .++++++++++++++++++++++++++++++++++++++++++++++++++++++====-----::==-::::::-=.      "
    "                 :+===++++++++++++++++++++++++++++++++++++++++====------:::::------------:--.       "
    "                  -+----==++++++++++++++++++++++++++++===------::::::------------------:--:         "
    "                   -+=--::----=====++++++=+======-----------------------------------:---:.          "
    "                    :+=----:::::::-----===---:-----==--=:..:....::::------------------:.            "
    "                     .-+==+=-::-----:=*=+-==-==-=#%@#-** .*=  .=- ::  ....:::-----==:.              "
    "                       -+++++=------:++=+-*--+-+**%@%@@%=#@#.:#@*---.:-:.:: .:-..::.                "
    "                     .=++++++++====-:-=-+-+:-=--=++*+#=%%+=%#%#%%#:--=.=:=-:.=-:..                  "
    "                   :=++++++++++==---=--------:-:--====:+= .#%=.*%%*-.-::.:.  .                      "
    "                .:=+++++++++===-=++=-------------::---=--:.-:  :*:-%*-::==.                         "
    "             .:=++++++++========-:-=+===------------::-------::....+: :-.-.                         "
    "            :*++===========-::.    .:-========---------------------::::::=-                         "
    "            .:::-----:::..              ..:--===+=====-=-----------------:.                         "
